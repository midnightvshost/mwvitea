(function(){
  const h1 = document.querySelector('.hero h1');
  if (!h1) return;
  const extras = document.querySelectorAll('.hero .reveal-in');
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  let timer = null;

  function wrapNode(node, chars){
    if (node.nodeType === 3){
      const frag = document.createDocumentFragment();
      node.textContent.split(/(\s+)/).forEach(part => {
        if (!part) return;
        if (/^\s+$/.test(part)){ frag.appendChild(document.createTextNode(' ')); return; }
        const w = document.createElement('span'); w.className = 'tw'; w.setAttribute('aria-hidden','true');
        [...part].forEach(ch => {
          const c = document.createElement('span'); c.className = 'tc'; c.textContent = ch;
          w.appendChild(c); chars.push(c);
        });
        frag.appendChild(w);
      });
      node.replaceWith(frag);
    } else if (node.nodeType === 1 && node.tagName !== 'BR'){
      [...node.childNodes].forEach(n => wrapNode(n, chars));
    }
  }

  function type(){
    clearTimeout(timer);
    // restore clean markup (current language) before wrapping
    const html = h1.getAttribute('data-plain') || h1.innerHTML;
    h1.innerHTML = html;
    h1.setAttribute('aria-label', h1.textContent.trim());
    h1.classList.remove('done'); h1.classList.add('typing');
    const chars = [];
    [...h1.childNodes].forEach(n => wrapNode(n, chars));
    const showExtras = () => extras.forEach((e,i) => setTimeout(() => e.classList.add('show'), i*180));
    if (reduce){ h1.classList.remove('typing'); chars.forEach(c => c.classList.add('on')); h1.classList.add('done'); extras.forEach(e => e.classList.add('show')); return; }
    extras.forEach(e => e.classList.remove('show'));
    let i = 0, prev = null;
    const step = () => {
      if (prev) prev.classList.remove('cur');
      if (i >= chars.length){ if (prev) prev.classList.add('cur'); h1.classList.add('done'); showExtras(); return; }
      const c = chars[i++]; c.classList.add('on','cur'); prev = c;
      const isBreak = i < chars.length && chars[i-1].parentNode !== chars[i].parentNode && /[.!?]/.test(c.textContent);
      timer = setTimeout(step, isBreak ? 380 : 55 + Math.random()*45);
    };
    timer = setTimeout(step, 500);
  }

  // hook: re-type whenever the language changes
  const _apply = applyLanguage;
  applyLanguage = function(lang){
    _apply(lang);
    h1.removeAttribute('data-plain');
    type();
  };
  type();
})();

