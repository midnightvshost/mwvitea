// ---- Partners: seamless left-to-right loop ----------------------------------
(function(){
  const marquee = document.querySelector('[data-partner-marquee]');
  if (!marquee) return;
  const track = marquee.querySelector('.partner-track');
  const original = track?.querySelector('.partner-set');
  if (!track || !original) return;

  const SPEED = 40; // pixels per second
  let resizeTimer;

  function build(){
    // Remove only generated copies. Never rebuild the original set while it is animating.
    track.querySelectorAll('.partner-set[data-clone]').forEach(node => node.remove());

    const setW = original.getBoundingClientRect().width;
    if (!setW) return;

    // Keep enough identical sets in the track so the next set is always ready
    // when the current one reaches the exact same starting position.
    const copies = Math.max(3, Math.ceil(marquee.clientWidth / setW) + 2);
    for (let i = 0; i < copies; i++){
      const clone = original.cloneNode(true);
      clone.setAttribute('data-clone', '');
      clone.setAttribute('aria-hidden', 'true');
      clone.querySelectorAll('a').forEach(a => a.setAttribute('tabindex', '-1'));
      track.appendChild(clone);
    }

    marquee.style.setProperty('--partner-shift', setW + 'px');
    marquee.style.setProperty('--partner-dur', (setW / SPEED) + 's');
  }

  // Build once after the page is ready. The previous script built twice
  // (immediately + window.load), which could visibly reset the marquee.
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', build, { once:true });
  } else {
    build();
  }

  window.addEventListener('resize', () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(build, 200);
  }, { passive:true });
})();


/* ===== Interactive "How it works" ===== */
(function(){
  const root = document.getElementById('processUI');
  if (!root) return;
  const rail = root.querySelector('.process-rail');
  const tabs = Array.from(root.querySelectorAll('.process-tab'));
  const panels = Array.from(root.querySelectorAll('.process-panel'));
  const last = tabs.length - 1;
  const reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  let cur = 0, timer = null, inView = false, hovering = false, touched = false;

  function go(i){
    i = Math.max(0, Math.min(last, i));
    cur = i;
    tabs.forEach((t, k) => {
      t.classList.toggle('active', k === i);
      t.classList.toggle('done', k < i);
      t.setAttribute('aria-selected', k === i ? 'true' : 'false');
      t.tabIndex = k === i ? 0 : -1;
    });
    panels.forEach((p, k) => { p.hidden = (k !== i); });
    rail.style.setProperty('--i', i);
  }

  function userGo(i, focusTab){
    touched = true;
    stopAuto();
    go(i);
    if (focusTab) tabs[cur].focus();
  }

  tabs.forEach((t, k) => {
    t.addEventListener('click', () => userGo(k, false));
    t.addEventListener('keydown', e => {
      let n = null;
      if (e.key === 'ArrowRight') n = Math.min(last, cur + 1);
      else if (e.key === 'ArrowLeft') n = Math.max(0, cur - 1);
      else if (e.key === 'Home') n = 0;
      else if (e.key === 'End') n = last;
      if (n !== null){ e.preventDefault(); userGo(n, true); }
    });
  });

  root.querySelectorAll('[data-go]').forEach(b => {
    b.addEventListener('click', () => userGo(cur + (b.dataset.go === 'next' ? 1 : -1), false));
  });

  /* Gentle autoplay: only while visible, never after the visitor interacts */
  function startAuto(){
    if (reduce || touched || timer || cur >= last) return;
    timer = setInterval(() => {
      if (!inView || hovering || touched) return;
      if (cur < last) go(cur + 1);
      if (cur >= last) stopAuto();
    }, 5500);
  }
  function stopAuto(){ if (timer){ clearInterval(timer); timer = null; } }

  root.addEventListener('mouseenter', () => { hovering = true; });
  root.addEventListener('mouseleave', () => { hovering = false; });
  root.addEventListener('focusin', () => { touched = true; stopAuto(); });

  if ('IntersectionObserver' in window){
    new IntersectionObserver(entries => {
      inView = entries[0].isIntersecting;
      if (inView) startAuto();
    }, { threshold: 0.4 }).observe(root);
  }

  go(0);
})();